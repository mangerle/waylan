//! 标准 QWERTY 物理键盘坐标、空间替换代价矩阵与邻键静态查找表

/// 获取标准 QWERTY 键盘字母的物理二维平面坐标 (x, y)
///
/// 坐标基于标准键盘物理中心距归一化：
/// - 行 0: Q~P 行 (y = 0.0)
/// - 行 1: A~L 行 (y = 1.0, x 轴右移约 0.25 错位)
/// - 行 2: Z~M 行 (y = 2.0, x 轴右移约 0.75 错位)
pub fn get_qwerty_coord(c: char) -> Option<(f32, f32)> {
    match c {
        'q' => Some((0.0, 0.0)),
        'w' => Some((1.0, 0.0)),
        'e' => Some((2.0, 0.0)),
        'r' => Some((3.0, 0.0)),
        't' => Some((4.0, 0.0)),
        'y' => Some((5.0, 0.0)),
        'u' => Some((6.0, 0.0)),
        'i' => Some((7.0, 0.0)),
        'o' => Some((8.0, 0.0)),
        'p' => Some((9.0, 0.0)),

        'a' => Some((0.25, 1.0)),
        's' => Some((1.25, 1.0)),
        'd' => Some((2.25, 1.0)),
        'f' => Some((3.25, 1.0)),
        'g' => Some((4.25, 1.0)),
        'h' => Some((5.25, 1.0)),
        'j' => Some((6.25, 1.0)),
        'k' => Some((7.25, 1.0)),
        'l' => Some((8.25, 1.0)),

        'z' => Some((0.75, 2.0)),
        'x' => Some((1.75, 2.0)),
        'c' => Some((2.75, 2.0)),
        'v' => Some((3.75, 2.0)),
        'b' => Some((4.75, 2.0)),
        'n' => Some((5.75, 2.0)),
        'm' => Some((6.75, 2.0)),
        _ => None,
    }
}

/// 获取标准 QWERTY 键盘字母在 0..26 范围内的索引
#[inline]
pub fn ascii_letter_idx(c: char) -> Option<usize> {
    if c.is_ascii_lowercase() {
        Some((c as u8 - b'a') as usize)
    } else if c.is_ascii_uppercase() {
        Some((c as u8 - b'A') as usize)
    } else {
        None
    }
}

